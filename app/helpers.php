/**
 * HTML Escaping (XSS protection)
 */
function e(?string $value): string {
    return htmlspecialchars((string) $value, ENT_QUOTES, 'UTF-8');
}

/**
 * Safe JSON encoding
 */
function json_encode_safe($data): string {
    return json_encode($data, JSON_HEX_TAG | JSON_HEX_AMP | JSON_HEX_APOS | JSON_HEX_QUOT | JSON_UNESCAPED_SLASHES);
}

/**
 * Safe redirect
 */
function redirect(string $url): void {
    header('Location: ' . $url);
    exit;
}

/**
 * JSON response
 */
function json_response(array $data, int $statusCode = 200): void {
    http_response_code($statusCode);
    header('Content-Type: application/json; charset=utf-8');
    echo json_encode($data, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES);
    exit;
}

/**
 * Current Authenticated User
 */
function auth_user(): ?array {
    if (empty($_SESSION['user_id'])) {
        return null;
    }
    static $user = null;
    if ($user === null || $user['id'] !== $_SESSION['user_id']) {
        $user = Database::fetchOne('SELECT * FROM users WHERE id = ? AND status = "active"', [$_SESSION['user_id']]);
        if (!$user) {
            unset($_SESSION['user_id'], $_SESSION['user_role']);
            return null;
        }
    }
    return $user;
}

function is_logged_in(): bool {
    return auth_user() !== null;
}

function is_admin(): bool {
    $u = auth_user();
    return $u && $u['role'] === 'admin';
}

function require_login(): void {
    if (!is_logged_in()) {
        set_flash('error', 'Please log in to continue.');
        redirect('/login');
    }
}

function require_admin(): void {
    if (!is_admin()) {
        set_flash('error', 'Access denied. Administrator privileges required.');
        redirect('/login');
    }
}

/**
 * Site Settings
 */
function get_setting(string $key, ?string $default = null): ?string {
    static $settingsCache = null;
    if ($settingsCache === null) {
        $rows = Database::fetchAll('SELECT key_name, key_value FROM settings');
        $settingsCache = [];
        foreach ($rows as $r) {
            $settingsCache[$r['key_name']] = $r['key_value'];
        }
    }
    return $settingsCache[$key] ?? $default;
}

/**
 * Currency Formatting
 */
function format_currency(float|int|string $amount, int $decimals = 4): string {
    $val = (float) $amount;
    $symbol = get_setting('currency_symbol', '$');
    return $symbol . number_format($val, $decimals);
}

/**
 * Date Formatting
 */
function format_date(?string $datetime, string $format = 'M d, Y H:i'): string {
    if (empty($datetime)) return '-';
    $tz = get_setting('timezone', 'UTC');
    try {
        $dt = new DateTime($datetime, new DateTimeZone('UTC'));
        if ($tz !== 'UTC') {
            $dt->setTimezone(new DateTimeZone($tz));
        }
        return $dt->format($format);
    } catch (Exception $e) {
        return $datetime;
    }
}

/**
 * System Audit Logging
 */
function log_audit(string $action, ?string $details = null, ?int $userId = null): void {
    try {
        $uid = $userId ?? ($_SESSION['user_id'] ?? null);
        $ip = $_SERVER['REMOTE_ADDR'] ?? '0.0.0.0';
        Database::insert(
            'INSERT INTO audit_logs (user_id, action, details, ip_address, created_at) VALUES (?, ?, ?, ?, NOW())',
            [$uid, $action, $details, $ip]
        );
    } catch (Exception $e) {
        error_log('Audit log failure: ' . $e->getMessage());
    }
}

/**
 * Status Badges
 */
function status_badge(string $status): string {
    $s = strtolower(trim($status));
    $classes = match ($s) {
        'completed', 'active', 'answered', 'success' => 'bg-emerald-500/10 text-emerald-400 border-emerald-500/20',
        'pending', 'open' => 'bg-amber-500/10 text-amber-400 border-amber-500/20',
        'processing', 'in_progress', 'user_reply' => 'bg-blue-500/10 text-blue-400 border-blue-500/20',
        'partial' => 'bg-purple-500/10 text-purple-400 border-purple-500/20',
        'canceled', 'cancelled', 'failed', 'banned', 'closed', 'inactive' => 'bg-rose-500/10 text-rose-400 border-rose-500/20',
        'refunded' => 'bg-cyan-500/10 text-cyan-400 border-cyan-500/20',
        default => 'bg-slate-500/10 text-slate-400 border-slate-500/20',
    };
    $label = ucfirst(str_replace('_', ' ', $s));
    return '<span class="inline-flex items-center px-2.5 py-0.5 rounded-full text-xs font-medium border ' . $classes . '">' . e($label) . '</span>';
}

